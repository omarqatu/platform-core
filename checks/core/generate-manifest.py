#!/usr/bin/env python3
"""Generates checks/core/manifest.json from the governing documents, by extraction (Check 2's input).

The documents, in order: PLATFORM_CORE v1.16, then its amendments by number (docs/PLATFORM_CORE_AMENDMENT_NN.md) —
the authority chain of CLAUDE.md. Each is read in both languages: every CREATE POLICY inside a ```sql block of the
body (before the appendices), verbatim. The Arabic governs, so the two must state the same statements in the same
order, comments aside; a mismatch is an error. The English text is what lands in the manifest.

- v1.16: the two templates (ON <t>) go under "templates", every other policy under its table, in the document's
  order. Five policies v1.16 states outside a sql block (OPEN_ITEMS 19) are added by name: tenant_isolation on four
  tables, from the template, and tenants_for_jobs from its plain block in §8.
- An amendment: no template, and no policy that an earlier document already states. A policy enters the manifest
  only once it is built — listed as "table.policy" in checks/core/amendment-policies-built.json; the rest is reported
  as pending. A listed name the amendment does not state is an error.

A policy written twice with different text is an error — a document must say one thing.

Usage: checks/core/generate-manifest.py [--diff | --check] [--root DIR]
  (none)    writes checks/core/manifest.json
  --diff    prints what changes against the current manifest, table by table, and writes nothing
  --check   the same, and exits 1 if anything changes (check-manifest-extraction)
  --root    the repository root to read (default: this file's repository; the self-test uses a copy)
"""
import json
import re
import sys
from pathlib import Path

BASE = ("PLATFORM_CORE v1.16", "docs/PLATFORM_CORE_v1_16_FROZEN.md", "docs/PLATFORM_CORE_v1_16_FROZEN_EN.md")
AMENDMENT = re.compile(r"PLATFORM_CORE_AMENDMENT_(\d+)\.md$")
APPENDIX = ("## Appendix", "## ملحق ")
# OPEN_ITEMS 19: stated by v1.16 outside a sql block. Not extractable, so named here — and nothing else is kept.
FROM_TEMPLATE = ("membership_roles", "role_permissions", "roles", "tenant_modules")
FROM_PLAIN_BLOCK = ("tenants", "tenants_for_jobs")
COMMENT = ("The manifest (PLATFORM_CORE v1.16 §3.6, Check 2). For every table in it, its complete policy set as the "
           "documents write it, each as the CREATE POLICY statement. Generated by extraction from {document} with "
           "checks/core/generate-manifest.py — never edited by hand; check-manifest-extraction compares the two. Every "
           "CREATE POLICY in a sql block of v1.16, plus the five it states outside one (tenant_isolation on "
           "membership_roles, role_permissions, roles, tenant_modules, and tenants_for_jobs in §8 — OPEN_ITEMS 19); "
           "and each amendment policy listed in checks/core/amendment-policies-built.json. A table not listed here "
           "must carry the templates alone.")


def statements(document: str):
    in_sql, current = False, []
    for line in document.replace("\r", "").split("\n"):
        if line.startswith(APPENDIX):
            break
        if line.startswith("```sql"):
            in_sql = True
            continue
        if line.startswith("```") and in_sql:
            in_sql = False
            if current:
                raise SystemExit(f"unterminated statement: {current[0]}")
            continue
        if not in_sql:
            continue
        if not current and not line.startswith("CREATE POLICY"):
            continue
        current.append(line)
        code = re.sub(r"--.*", "", line).rstrip()
        if code.endswith(";"):
            yield "\n".join(current)
            current = []


def without_comments(stmt: str) -> str:
    return "\n".join(re.sub(r"\s*--.*", "", line).rstrip() for line in stmt.split("\n"))


def key_of(stmt: str):
    _, _, name, _, table = stmt.split()[:5]
    return table, name


def read(root: Path, arabic: str, english: str):
    """The English statements, after checking the Arabic states the same ones."""
    ar = list(statements((root / arabic).read_text(encoding="utf-8")))
    en = list(statements((root / english).read_text(encoding="utf-8")))
    if [without_comments(s) for s in ar] != [without_comments(s) for s in en]:
        ar_keys, en_keys = [key_of(s) for s in ar], [key_of(s) for s in en]
        if ar_keys != en_keys:
            raise SystemExit(f"{english} does not state the same policies as {arabic}: "
                             f"{sorted(set(ar_keys) ^ set(en_keys)) or 'a different order'}")
        drifted = [f"{n} ON {t}" for (t, n), a, e in zip(en_keys, ar, en) if without_comments(a) != without_comments(e)]
        raise SystemExit(f"{english} drifted from {arabic} (the Arabic governs): {', '.join(drifted)}")
    return en


def documents(root: Path):
    yield BASE
    amendments = sorted((int(m.group(1)), p.name) for p in (root / "docs").glob("PLATFORM_CORE_AMENDMENT_*.md")
                        if (m := AMENDMENT.search(p.name)))
    for number, name in amendments:
        english = f"docs/{name[:-3]}_EN.md"
        if not (root / english).exists():
            raise SystemExit(f"docs/{name} has no translation ({english})")
        yield f"Amendment {number:02d}", f"docs/{name}", english


def extract(root: Path):
    built = json.loads((root / "checks/core/amendment-policies-built.json").read_text(encoding="utf-8"))
    templates, tables, seen, pending, names = {}, {}, {}, [], []

    def add(table, name, stmt, first=False):
        if (table, name) in seen:
            if seen[(table, name)] != stmt:
                raise SystemExit(f"{name} ON {table} is written twice, with different text")
            return
        seen[(table, name)] = stmt
        policies = tables.setdefault(table, [])
        policies.insert(0, stmt) if first else policies.append(stmt)

    for document, arabic, english in documents(root):
        names.append(document)
        stmts = read(root, arabic, english)
        if document == BASE[0]:
            for stmt in stmts:
                table, name = key_of(stmt)
                if table == "<t>":
                    templates[name] = stmt
                else:
                    add(table, name, stmt)
            for table in FROM_TEMPLATE:
                add(table, "tenant_isolation", templates["tenant_isolation"].replace("<t>", table), first=True)
            add(*FROM_PLAIN_BLOCK, plain_block(root / english, *FROM_PLAIN_BLOCK))
            continue

        number = document.split()[-1]
        listed = set(built.get(number, []))
        stated = set()
        for stmt in stmts:
            table, name = key_of(stmt)
            if table == "<t>":
                raise SystemExit(f"{document} redefines the template {name}")
            if (table, name) in seen:
                raise SystemExit(f"{document} restates {name} ON {table}, which an earlier document states")
            stated.add(f"{table}.{name}")
            if f"{table}.{name}" in listed:
                add(table, name, stmt)
            else:
                pending.append(f"{document}: {table}.{name}")
        unknown = sorted(listed - stated)
        if unknown:
            raise SystemExit(f"amendment-policies-built.json lists what {document} does not state: {', '.join(unknown)}")
    unknown = sorted(set(built) - {d.split()[-1] for d in names if d.startswith("Amendment")} - {"_comment"})
    if unknown:
        raise SystemExit(f"amendment-policies-built.json names amendments that do not exist: {', '.join(unknown)}")
    return " + ".join(names), templates, tables, pending


def plain_block(path: Path, table: str, name: str) -> str:
    """A policy written in a plain (non-sql) block: its lines, dedented, up to the semicolon."""
    lines = path.read_text(encoding="utf-8").replace("\r", "").split("\n")
    for i, line in enumerate(lines):
        if line.strip().startswith(f"CREATE POLICY {name} ON {table}"):
            indent = len(line) - len(line.lstrip())
            stmt = []
            for following in lines[i:]:
                stmt.append(following[indent:])
                if following.rstrip().endswith(";"):
                    return "\n".join(stmt)
    raise SystemExit(f"{name} ON {table} is not in {path.name}")


def main():
    args = sys.argv[1:]
    mode = next((a for a in args if a in ("--diff", "--check")), None)
    root = Path(args[args.index("--root") + 1]) if "--root" in args else Path(__file__).resolve().parents[2]
    manifest_path = root / "checks/core/manifest.json"

    document, templates, tables, pending = extract(root)
    current = json.loads(manifest_path.read_text(encoding="utf-8"))
    name_of = lambda s: s.split()[2]

    report = []
    if current.get("document") != document:
        report.append(f"document: {current.get('document')} → {document}")
    for name in sorted(set(templates) | set(current["templates"])):
        if templates.get(name) != current["templates"].get(name):
            report.append(f"template {name}: changed")
    for table in list(current["tables"]) + [t for t in tables if t not in current["tables"]]:
        have = {name_of(s): s for s in current["tables"].get(table, [])}
        want = {name_of(s): s for s in tables.get(table, [])}
        for name in want.keys() - have.keys():
            report.append(f"{table}: added    {name}")
        for name in have.keys() - want.keys():
            report.append(f"{table}: removed  {name} (in the manifest, not extracted from the documents)")
        replaced = [name for name in want.keys() & have.keys() if want[name] != have[name]]
        report += [f"{table}: replaced {name}" for name in sorted(replaced)]
    for p in pending:
        print(f"pending (not built): {p}")
    print("\n".join(report) if report else "manifest.json matches the documents")

    if mode == "--check":
        sys.exit(1 if report else 0)
    if mode == "--diff":
        return

    # Order carries no meaning for Check 2; keep the manifest's (tables, and policies within a table), and append what
    # is new in the documents' order, so a regeneration changes only what changed.
    ordered = {}
    for table in list(current["tables"]) + [t for t in tables if t not in current["tables"]]:
        if table not in tables:
            continue
        want = {name_of(s): s for s in tables[table]}
        kept = [name_of(s) for s in current["tables"].get(table, []) if name_of(s) in want]
        ordered[table] = [want[n] for n in kept] + [s for n, s in want.items() if n not in kept]
    current["_comment"] = COMMENT.format(document=document)
    current["document"] = document
    current["templates"] = templates
    current["tables"] = ordered
    manifest_path.write_text(json.dumps(current, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{manifest_path}: {len(templates)} templates, {sum(map(len, ordered.values()))} policies on "
          f"{len(ordered)} tables; {len(pending)} pending")


main()
